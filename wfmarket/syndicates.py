def item_name(item: dict[str, Any], language: str = "en") -> str:
    i18n = item.get("i18n") or {}
    localized = i18n.get(language) or i18n.get("en") or {}
    return str(localized.get("name") or item.get("item_name") or item.get("slug") or "")


def item_tags(item: dict[str, Any]) -> tuple[str, ...]:
    return tuple(str(tag) for tag in (item.get("tags") or ()))


def item_kind(item: dict[str, Any]) -> str:
    tags = item_tags(item)
    if "arcane_enhancement" in tags:
        return "Arcane"
    if "augment" in tags:
        return "Augment"
    return "Mod"


def is_syndicate_item(item: dict[str, Any], syndicate: Syndicate) -> bool:
    return str(item.get("slug") or "") in syndicate.slugs


def select_syndicate_items(
    items: Iterable[dict[str, Any]], syndicate: Syndicate
) -> list[dict[str, Any]]:
    selected = [item for item in items if is_syndicate_item(item, syndicate)]
    return sorted(selected, key=lambda item: item_name(item).casefold())
